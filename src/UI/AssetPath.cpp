#include "AssetPath.h"

#include "Platform/Factory.h"

// version.h provides TASKSMACK_PROJECT_NAME_LOWER, which is set by CMake from
// ${PROJECT_NAME_LOWER} — the same variable used in the install() destination.
// This ensures the runtime search path matches the installed path without duplication.
#include "version.h"

#include <spdlog/spdlog.h>

#include <array>
#include <filesystem>
#include <string_view>

namespace UI
{

namespace
{

/// Get directory containing the current executable via the platform path provider.
[[nodiscard]] std::filesystem::path executableDir()
{
    static const auto dir = []
    {
        auto provider = Platform::makePathProvider();
        return provider->getExecutableDir();
    }();
    return dir;
}

} // namespace

std::filesystem::path findAssetsDir()
{
    const auto exeDir = executableDir();

    // TASKSMACK_PROJECT_NAME_LOWER is generated by CMake from ${PROJECT_NAME_LOWER},
    // which is the same variable used in the install() destination (share/<name>/assets).
    const std::string_view APP_NAME = TASKSMACK_PROJECT_NAME_LOWER;

    // lexically_normal() resolves ".." without requiring the path to exist;
    // existence is validated below via std::filesystem::exists().
    const std::array<std::filesystem::path, 3> candidates = {
        exeDir / "assets",
        exeDir / "share" / APP_NAME / "assets",
        (exeDir / ".." / "share" / APP_NAME / "assets").lexically_normal(),
    };

    for (const auto& candidate : candidates)
    {
        if (std::filesystem::exists(candidate / "fonts"))
        {
            spdlog::debug("Assets directory found: {}", candidate.string());
            return candidate;
        }
    }

    spdlog::warn("Assets directory not found in any expected location; defaulting to {}", candidates[0].string());
    return candidates[0];
}

} // namespace UI
