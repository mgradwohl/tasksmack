#!/usr/bin/env python3
"""Generate src/Platform/UnicodeCaseFoldTable.h: Unicode simple case folding (#4302, the UTF-8 audit's D2).

Simple case folding is CaseFolding.txt's C and S mappings: one code point to one code point, with no F (full,
one-to-many) and no T (Turkish) mappings. It is derived from Python's unicodedata, so the table follows the
Unicode version this interpreter ships (printed into the header):
  - C: a code point whose str.casefold() is one other code point maps to it;
  - S: one whose casefold() is several (an F mapping) maps to its single-code-point str.lower(), if that
    differs (U+1E9E -> U+00DF, U+1F88 -> U+1F80), else to itself;
  - U+0130 (Turkish I with dot) has only F and T mappings, so it maps to itself, as CaseFolding.txt has it.

Usage: python3 tools/gen-unicode-case-fold.py > src/Platform/UnicodeCaseFoldTable.h
"""

import sys
import unicodedata


def simple_fold(cp: int) -> int:
    ch = chr(cp)
    folded = ch.casefold()
    if len(folded) == 1:
        return ord(folded)
    lowered = ch.lower()
    if len(lowered) == 1:
        return ord(lowered)
    return cp


def main() -> int:
    pairs = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        to = simple_fold(cp)
        if to != cp:
            pairs.append((cp, to))
    out = sys.stdout
    out.write("#pragma once\n\n")
    out.write("// GENERATED by tools/gen-unicode-case-fold.py from Unicode "
              f"{unicodedata.unidata_version}: do not edit.\n")
    out.write("// Unicode simple case folding (CaseFolding.txt statuses C and S; no F, no T), as (code point, fold) pairs\n")
    out.write("// sorted by code point, for Utf8CaseFold.h's binary search (#4302).\n\n")
    out.write("#include <array>\n#include <cstdint>\n#include <utility>\n\n")
    out.write("namespace Platform::UnicodeCaseFold\n{\n\n")
    out.write(f'inline constexpr char UNICODE_VERSION[] = "{unicodedata.unidata_version}"; // NOLINT(cppcoreguidelines-avoid-c-arrays,modernize-avoid-c-arrays)\n\n')
    out.write(f"inline constexpr std::array<std::pair<std::uint32_t, std::uint32_t>, {len(pairs)}> SIMPLE_FOLDS{{{{\n")
    for cp, to in pairs:
        out.write(f"    {{0x{cp:04X}, 0x{to:04X}}},\n")
    out.write("},\n};\n\n} // namespace Platform::UnicodeCaseFold\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
